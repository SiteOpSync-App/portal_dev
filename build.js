// Cloudflare Pages build for one client (or dev) site.
//   Build command: node build.js     Build output directory: dist     Environment variable NODE_VERSION: 20
// Copies the static files into dist/ and writes config.js and manifest.json from the project's environment variables:
//   APPS_SCRIPT_URL (required)  CLIENT_ID  COMPANY_NAME  SHORT_NAME  LOGO (file name in the repo)  SITE_ENV ("dev" shows a DEV ribbon)
const fs = require("fs");
const path = require("path");

const env = process.env;
const company = env.COMPANY_NAME || "i-Glaze Limited";
const cfg = {
    clientId: env.CLIENT_ID || "i-glazeltd",
    companyName: company,
    shortName: env.SHORT_NAME || company.replace(/\s+(Limited|Ltd)\.?$/i, ""),
    appsScriptUrl: env.APPS_SCRIPT_URL || "",
    logo: env.LOGO || "company logo1.png",
    env: env.SITE_ENV === "dev" ? "dev" : "prod"
};
if (!/^https:\/\/script\.google\.com\/macros\/s\/.+\/exec$/.test(cfg.appsScriptUrl)) {
    console.error("APPS_SCRIPT_URL must be set to the client's Apps Script web app URL (https://script.google.com/macros/s/.../exec).");
    process.exit(1);
}

const root = __dirname, out = path.join(root, "dist");
const keep = /\.(html|js|css|json|png|jpg|jpeg|svg|ico|webp|txt)$/i;
const skip = new Set(["build.js", "package.json", "package-lock.json"]);

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out);
fs.readdirSync(root).forEach(function (f) {
    if (skip.has(f) || !keep.test(f) || !fs.statSync(path.join(root, f)).isFile()) return;
    fs.copyFileSync(path.join(root, f), path.join(out, f));
});
if (!fs.existsSync(path.join(out, cfg.logo))) console.warn("Warning: logo file '" + cfg.logo + "' was not found in the repo.");

fs.writeFileSync(path.join(out, "config.js"), "// Generated by build.js from the Pages environment variables. Do not edit.\nwindow.SITE_CONFIG = " + JSON.stringify(cfg, null, 4) + ";\n");

const mpath = path.join(out, "manifest.json");
if (fs.existsSync(mpath)) {
    const m = JSON.parse(fs.readFileSync(mpath, "utf8"));
    m.name = cfg.shortName + " SiteOpSync" + (cfg.env === "dev" ? " (dev)" : "");
    m.short_name = cfg.env === "dev" ? "SiteOpSync Dev" : "SiteOpSync";
    fs.writeFileSync(mpath, JSON.stringify(m, null, 2));
}
console.log("Built " + cfg.clientId + " (" + cfg.env + ") with " + fs.readdirSync(out).length + " files");
